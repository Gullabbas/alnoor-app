class AppLocaleNotifier extends ChangeNotifier {
  Locale _locale = const Locale('en');

  Locale get locale => _locale;
  bool get isUrdu => _locale.languageCode == 'ur';
  TextDirection get textDirection => isUrdu ? TextDirection.rtl : TextDirection.ltr;

  void setLocale(Locale newLocale) {
    if (_locale != newLocale) {
      _locale = newLocale;
      notifyListeners();
    }
  }

  void toggleLocale() {
    if (_locale.languageCode == 'en') {
      setLocale(const Locale('ur'));
    } else {
      setLocale(const Locale('en'));
    }
  }
}

extension BuildContextL10n on BuildContext {
  String tr(String key) {
    final isUrdu = Directionality.of(this) == TextDirection.rtl;
    return AppStrings.get(key, isUrdu ? 'ur' : 'en');
  }
}
